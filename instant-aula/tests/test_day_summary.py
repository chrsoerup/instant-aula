# --- single rules, ordinary weeks ---------------------------------------------


def day(notes=None, timetable=()):
    return Day(datetime.date(2026, 11, 24), list(timetable), notes or {})


@pytest.mark.parametrize("notes,timetable,title", [
    # PE with no cancellation -> gear from the timetable
    ({}, ["IDR"], "🎒 Idrætstøj"),
    ({"Dansk": ["Vi læser videre i bogen."]}, ["DAN", "IDR"], "🎒 Idrætstøj"),
    # "medbring idrætstøj" already says it -> not twice
    ({"Idræt": ["Husk at medbringe idrætstøj og håndklæde."]}, ["IDR"],
     "🎒 Medbring idrætstøj + håndklæde"),
    ({"Idræt": ["Idræt er aflyst pga. skolefoto."]}, ["IDR"], "🎒 Skolefoto"),
    # homework needs a homework phrase
    ({"Matematik": ["Side 10-11 i bogen skal laves"]}, [], "🎒 Lektier: Mat"),
    ({"Matematik": ["Lektie: opgave 4 og 5"], "Engelsk": ["Øv gloserne til næste gang"]}, [],
     "🎒 Lektier: Mat, Engelsk"),
    ({"Dansk": ["Vi skriver i en opgave om venskab."]}, [], "📝 1 note"),
    # imperative "Husk", not "huske"
    ({"Klassen": ["HUSK: underskrevet seddel om lejrskole senest fredag"]}, [],
     "🎒 Lejrskole · Husk underskrevet seddel om lejrskole senest…"),
    ({"Dansk": ["Kan I huske, hvad vi læste sidst?"]}, [], "📝 1 note"),
    ({"Klassen": ["I morgen skal I tage madpakke med."]}, [], "🎒 Medbring madpakke"),
    # nothing at all -> no event
    ({}, ["DAN", "MAT"], None),
])
def test_rules(notes, timetable, title):
    assert summarise(day(notes, timetable)).title == title


def test_meebook_date_across_new_year():
    monday = datetime.date(2026, 12, 28)  # ISO week 2026-W53 runs into January
    assert meebook_date("fredag 1. jan.", monday) == datetime.date(2027, 1, 1)
    assert meebook_date("mandag 28. dec.", monday) == datetime.date(2026, 12, 28)
